export default function EventsPage() {
  const { data, isLoading, isError } = useSecurityEvents(1, 200);

  const events = data?.items ?? [];
  const total = data?.total ?? 0;

  const blockedCount = events.filter((event) =>
    event.decision.toUpperCase().includes("BLOCK"),
  ).length;

  const warningCount = events.filter((event) =>
    event.decision.toUpperCase().includes("WARN"),
  ).length;

  const allowedCount = events.filter(
    (event) => event.decision.toUpperCase() === "ALLOW",
  ).length;

  const queryState = isLoading
    ? "Loading"
    : isError
      ? "Unavailable"
      : "Available";

  return (
    <div className="space-y-5">
      {/* Header */}
      <section className="security-surface relative overflow-hidden p-5 sm:p-6">
        <div className="security-grid pointer-events-none absolute inset-0 opacity-25" />

        <div className="relative">
          <div className="flex flex-wrap items-center gap-2">
            <div className="flex items-center gap-2 text-[10px] font-semibold uppercase tracking-[0.2em] text-indigo-600 dark:text-indigo-400">
              <Activity className="size-3.5" />
              Security Telemetry
            </div>

            <span className="h-1 w-1 rounded-full bg-slate-200" />

            <span className="font-mono text-[9px] uppercase tracking-[0.16em] text-slate-500 dark:text-slate-400">
              Runtime / Events
            </span>
          </div>

          <div className="mt-5 flex flex-col gap-5 lg:flex-row lg:items-end lg:justify-between">
            <div>
              <h1 className="text-2xl font-semibold tracking-tight text-slate-900 dark:text-slate-100 sm:text-3xl">
                Security Events
              </h1>

              <p className="mt-2 max-w-2xl text-sm leading-6 text-slate-500 dark:text-slate-400">
                Investigate security decisions generated by SentinelX agents,
                policies, and runtime enforcement.
              </p>
            </div>

            <StreamIndicator state={queryState} isError={isError} />
          </div>
        </div>
      </section>

      {/* Metrics */}
      <section className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
        <MetricCard
          label="Total Events"
          value={isLoading ? "—" : isError ? "!" : total.toString()}
          detail="Recorded security activity"
          icon={Activity}
          tone="cyan"
        />

        <MetricCard
          label="Blocked"
          value={isLoading ? "—" : isError ? "!" : blockedCount.toString()}
          detail="Blocked decisions on this page"
          icon={Ban}
          tone="red"
        />

        <MetricCard
          label="Warnings"
          value={isLoading ? "—" : isError ? "!" : warningCount.toString()}
          detail="Warnings on this page"
          icon={AlertTriangle}
          tone="amber"
        />

        <MetricCard
          label="Allowed"
          value={isLoading ? "—" : isError ? "!" : allowedCount.toString()}
          detail="ALLOW decisions on this page"
          icon={ShieldCheck}
          tone="emerald"
        />
      </section>

      {/* Event stream */}
      <section className="security-surface overflow-hidden">
        <div className="flex items-center gap-2 border-b border-slate-200 dark:border-slate-800 px-5 py-4">
          <div className="flex size-7 items-center justify-center rounded-lg border border-indigo-400/10 bg-indigo-400/[0.05]">
            <Activity className="size-3.5 text-indigo-600 dark:text-indigo-400" />
          </div>
          <div>
            <h2 className="text-sm font-semibold text-slate-800 dark:text-slate-100">Event Log</h2>
            <p className="text-[10px] text-slate-500 dark:text-slate-400">
              Searchable, sortable security event records
            </p>
          </div>
        </div>

        {isLoading ? (
          <SkeletonTable rows={8} />
        ) : isError ? (
          <EventsErrorState />
        ) : events.length === 0 ? (
          <EventsEmptyState />
        ) : (
          <DataTable<SecurityEvent>
            data={events}
            searchable={(e) =>
              `${e.event_type} ${e.action} ${e.decision} ${e.reason ?? ""}`
            }
            searchPlaceholder="Search events…"
            csvFilename="sentinelx-events.csv"
            columns={eventColumns}
          />
        )}
      </section>

      {/* Event record summary */}
      <section className="grid gap-3 md:grid-cols-3">
        <OperationalSignal
          icon={Activity}
          label="Event query"
          value={isLoading ? "Loading" : isError ? "Unavailable" : "Available"}
          detail="Security event records retrieved"
          tone={isError ? "red" : "cyan"}
        />

        <OperationalSignal
          icon={ShieldCheck}
          label="Policy decisions"
          value="Recorded"
          detail="Outcomes included in this event log"
          tone="emerald"
        />

        <OperationalSignal
          icon={Clock3}
          label="Event retention"
          value={total.toString()}
          detail="Events currently indexed"
          tone="cyan"
        />
      </section>
    </div>
  );
}

function StreamIndicator({
  state,
  isError,
}: {
  state: string;
  isError: boolean;
}) {
  const tone = isError
    ? "red"
    : state === "Loading"
      ? "amber"
      : "emerald";

  const classes = {
    red: "border-red-400/15 bg-red-400/[0.05] text-red-600 dark:text-red-400",
    amber: "border-amber-400/15 bg-amber-400/[0.05] text-amber-600 dark:text-amber-400",
    emerald:
      "border-emerald-400/15 bg-emerald-400/[0.05] text-emerald-600 dark:text-emerald-400",
  }[tone];

  const dot = {
    red: "bg-red-400",
    amber: "bg-amber-400",
    emerald: "bg-emerald-400",
  }[tone];

  return (
    <div
      className={`inline-flex w-fit items-center gap-2 rounded-full border px-3 py-1.5 ${classes}`}
    >
      <span className={`size-1.5 rounded-full ${dot}`} />

      <span className="text-[9px] font-semibold uppercase tracking-[0.16em]">
        Event query {state}
      </span>
    </div>
  );
}

