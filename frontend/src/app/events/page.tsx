
"use client";

import {
  Activity,
  AlertTriangle,
  Ban,
  CheckCircle2,
  Clock3,
  Filter,
  LoaderCircle,
  ShieldAlert,
  ShieldCheck,
  Terminal,
} from "lucide-react";

import { useSecurityEvents } from "@/features/events/use-security-events";

function DecisionBadge({ decision }: { decision: string }) {
  const normalized = decision.toUpperCase();
  const blocked = normalized.includes("BLOCK");
  const warning = normalized.includes("WARN");

  const style = blocked
    ? "border-red-400/15 bg-red-400/[0.06] text-red-300"
    : warning
      ? "border-amber-400/15 bg-amber-400/[0.06] text-amber-300"
      : "border-emerald-400/15 bg-emerald-400/[0.06] text-emerald-300";

  return (
    <span
      className={`inline-flex items-center gap-1.5 rounded-full border px-2 py-1 text-[8px] font-semibold uppercase tracking-[0.14em] ${style}`}
    >
      {blocked ? (
        <Ban className="size-3" />
      ) : warning ? (
        <AlertTriangle className="size-3" />
      ) : (
        <CheckCircle2 className="size-3" />
      )}
      {normalized}
    </span>
  );
}

function formatDate(value: string) {
  const date = new Date(value);

  if (Number.isNaN(date.getTime())) {
    return "—";
  }

  return date.toLocaleString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

