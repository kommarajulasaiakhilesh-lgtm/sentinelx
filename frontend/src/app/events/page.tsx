function StreamIndicator({
  state,
  isError,
}: {
  state: string;
  isError: boolean;
}) {
  const tone = isError
    ? "red"
    : state === "Synchronizing"
      ? "amber"
      : "emerald";

  const classes = {
    red: "border-red-400/15 bg-red-400/[0.05] text-red-300",
    amber: "border-amber-400/15 bg-amber-400/[0.05] text-amber-300",
    emerald:
      "border-emerald-400/15 bg-emerald-400/[0.05] text-emerald-300",
  }[tone];

  const dot = {
    red: "bg-red-400",
    amber: "bg-amber-400",
    emerald: "bg-emerald-400",
  }[tone];

  return (
    <div
      className={`inline-flex w-fit items-center gap-2 rounded-full border px-3 py-1.5 ${classes}`}
    >
      <span
        className={`size-1.5 rounded-full ${dot} ${
          state === "Operational" ? "animate-pulse" : ""
        }`}
      />

      <span className="text-[9px] font-semibold uppercase tracking-[0.16em]">
        Stream {state}
      </span>
    </div>
  );
}

function MetricCard({
  label,
  value,
  detail,
  icon: Icon,
  tone,
}: {
  label: string;
  value: string;
  detail: string;
  icon: typeof Activity;
  tone: "cyan" | "red" | "amber" | "emerald";
}) {
  const styles = {
    cyan: {
      icon: "border-cyan-400/10 bg-cyan-400/[0.05] text-cyan-300",
      value: "text-white",
    },
    red: {
      icon: "border-red-400/10 bg-red-400/[0.05] text-red-300",
      value: "text-red-300",
    },
    amber: {
      icon: "border-amber-400/10 bg-amber-400/[0.05] text-amber-300",
      value: "text-amber-300",
    },
    emerald: {
      icon: "border-emerald-400/10 bg-emerald-400/[0.05] text-emerald-300",
      value: "text-emerald-300",
    },
  }[tone];

  return (
    <div className="security-surface security-surface-hover p-4">
      <div className="flex items-start justify-between gap-3">
        <span className="text-[9px] font-semibold uppercase tracking-[0.17em] text-slate-600">
          {label}
        </span>

        <div
          className={`flex size-8 shrink-0 items-center justify-center rounded-lg border ${styles.icon}`}
        >
          <Icon className="size-4" />
        </div>
      </div>

      <div
        className={`mt-4 text-2xl font-semibold tracking-tight ${styles.value}`}
      >
        {value}
      </div>

      <p className="mt-1 text-[10px] text-slate-600">{detail}</p>
    </div>
  );
}

function EventRow({
  event,
  index,
}: {
  event: {
    id: number;
    agent_id: number;
    policy_id?: number | null;
    event_type: string;
    action?: string | null;
    decision: string;
    reason?: string | null;
    created_at: string;
  };
  index: number;
}) {
  const normalized = event.decision.toUpperCase();
  const blocked = normalized.includes("BLOCK");
  const warning = normalized.includes("WARN");

  const accent = blocked
    ? "border-l-red-400/60"
    : warning
      ? "border-l-amber-400/60"
      : "border-l-emerald-400/50";

  const iconStyle = blocked
    ? "border-red-400/10 bg-red-400/[0.04] text-red-300"
    : warning
      ? "border-amber-400/10 bg-amber-400/[0.04] text-amber-300"
      : "border-cyan-400/10 bg-cyan-400/[0.04] text-cyan-300";

  return (
    <article
      className={`group border-l-2 ${accent} px-5 py-4 transition-colors hover:bg-white/[0.015]`}
    >
      <div className="flex flex-col gap-4 xl:flex-row xl:items-center xl:justify-between">
        <div className="flex min-w-0 items-start gap-3">
          <div
            className={`flex size-9 shrink-0 items-center justify-center rounded-lg border ${iconStyle}`}
          >
            {blocked ? (
              <Ban className="size-4" />
            ) : warning ? (
              <AlertTriangle className="size-4" />
            ) : (
              <Activity className="size-4" />
            )}
          </div>

          <div className="min-w-0">
            <div className="flex flex-wrap items-center gap-2">
              <span className="font-mono text-[9px] text-slate-700">
                EVT-{String(index + 1).padStart(2, "0")}
              </span>

              <span className="text-[9px] uppercase tracking-[0.12em] text-slate-700">
                #{event.id}
              </span>

              <DecisionBadge decision={event.decision} />
            </div>

            <h3 className="mt-1 truncate text-sm font-semibold text-slate-200">
              {event.event_type}
            </h3>

            <p className="mt-1 max-w-2xl truncate text-[10px] text-slate-600">
              {event.reason || "No decision reason recorded"}
            </p>
          </div>
        </div>

        <div className="grid grid-cols-2 gap-x-7 gap-y-3 sm:grid-cols-4 xl:min-w-[520px]">
          <EventMetadata
            label="Agent"
            value={`#${event.agent_id}`}
          />

          <EventMetadata
            label="Action"
            value={event.action || "No action recorded"}
          />

          <EventMetadata
            label="Policy"
            value={event.policy_id ? `#${event.policy_id}` : "None"}
          />

          <EventMetadata
            label="Timestamp"
            value={formatDate(event.created_at)}
            icon
          />
        </div>
      </div>
    </article>
  );
}

function EventMetadata({
  label,
  value,
  icon = false,
}: {
  label: string;
  value: string;
  icon?: boolean;
}) {
  return (
    <div className="min-w-0">
      <div className="flex items-center gap-1.5 text-[8px] font-medium uppercase tracking-[0.14em] text-slate-700">
        {icon && <Clock3 className="size-3" />}
        {label}
      </div>

      <div className="mt-1 truncate font-mono text-[10px] text-slate-400">
        {value}
      </div>
    </div>
  );
}

